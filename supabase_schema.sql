-- EcoMove : schéma de base de données pédagogique pour Supabase / PostgreSQL
-- À exécuter dans Supabase > SQL Editor après avoir activé Supabase Auth.
-- Les utilisateurs s'inscrivent via Supabase Auth : ne jamais stocker les mots de passe dans une table.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'client' check (role in ('client','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.stations (
  id bigint generated by default as identity primary key,
  name text not null,
  address text not null,
  latitude numeric(9,6),
  longitude numeric(9,6),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.vehicles (
  id bigint generated by default as identity primary key,
  station_id bigint references public.stations(id),
  name text not null,
  vehicle_type text not null check (vehicle_type in ('Velo','Trottinette')),
  hourly_price numeric(8,2) not null check (hourly_price >= 0),
  status text not null default 'available' check (status in ('available','reserved','maintenance')),
  description text,
  created_at timestamptz not null default now()
);

create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  vehicle_id bigint not null references public.vehicles(id),
  station_id bigint not null references public.stations(id),
  start_at timestamptz not null,
  duration_hours integer not null check (duration_hours between 1 and 24),
  quantity integer not null default 1 check (quantity between 1 and 5),
  total_price numeric(8,2) not null check (total_price >= 0),
  status text not null default 'pending' check (status in ('pending','confirmed','cancelled','completed')),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.stations enable row level security;
alter table public.vehicles enable row level security;
alter table public.reservations enable row level security;

-- Lecture publique des stations et véhicules actifs.
create policy "Stations visibles" on public.stations for select using (is_active = true);
create policy "Véhicules disponibles visibles" on public.vehicles for select using (status = 'available');

-- Un client lit et crée uniquement ses propres réservations.
create policy "Lire ses réservations" on public.reservations
for select to authenticated using (auth.uid() = user_id);
create policy "Créer ses réservations" on public.reservations
for insert to authenticated with check (auth.uid() = user_id);

-- Chaque utilisateur lit son profil.
create policy "Lire son profil" on public.profiles
for select to authenticated using (auth.uid() = id);

